// DTCG tokens -> CSS custom properties (design-system.md, Layer 1).
// Light tokens (plus the theme-independent ones) go to :root; dark tokens follow the OS preference.
// Output: src/styles/tokens.css (generated, not committed).
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

async function render(sources) {
  const dictionary = new StyleDictionary({
    log: { warnings: 'error', verbosity: 'default' },
    source: sources.map((file) => join(root, 'design', 'tokens', file)),
    platforms: {
      css: {
        // Colours stay in OKLCH: the default css transform group would rewrite them to hex.
        transforms: ['name/kebab'],
        files: [
          { destination: 'tokens.css', format: 'css/variables', options: { selector: ':root' } },
        ],
      },
    },
  });
  const [file] = await dictionary.formatPlatform('css');
  return file.output.replace(/\/\*\*[\s\S]*?\*\/\n/, '').trim();
}

const light = await render(['light.tokens.json', 'shared.tokens.json']);
const dark = await render(['dark.tokens.json']);
const indented = dark
  .split('\n')
  .map((line) => `  ${line}`)
  .join('\n');

const css = `/* Generated by design/build-tokens.mjs from design/tokens/*.json. Do not edit. */
${light}

@media (prefers-color-scheme: dark) {
${indented}
}
`;

await mkdir(join(root, 'src', 'styles'), { recursive: true });
await writeFile(join(root, 'src', 'styles', 'tokens.css'), css);
console.log('tokens.css written');
